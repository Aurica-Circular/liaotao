#!/usr/bin/env bash
# verify.sh — The judge. One command, one answer: GREEN or RED.
#
# Runs every check in order and stops at the first failure:
#   1. The project builds (interface and Rust)
#   2. Automated tests pass
#   3. No user-visible text is hard-coded (strings live in src/i18n/en.json)
#   4. No colour is hard-coded (colours live in tailwind.config.js)
#   5. No source file exceeds 350 lines
#   6. No dependency was added or changed without approval (tag: deps-approved)
#   7. No secret and no personal path in the repository
#
# Usage:
#   ./verify.sh          all checks above
#   ./verify.sh --live   also runs tests that need a real engine (Ollama);
#                        those tests are marked #[ignore] in Rust
#
# Do not edit this file to make a task pass. A red verdict is a failed task.

set -uo pipefail

ROOT="$(cd "$(dirname "$0")" && pwd)"
cd "$ROOT" || exit 2

LIVE=0
[[ "${1:-}" == "--live" ]] && LIVE=1

MAX_LINES=350
APPROVED_TAG="deps-approved"
TOTAL=7

if [[ -t 1 ]]; then RED=$'\e[31m'; GREEN=$'\e[32m'; DIM=$'\e[2m'; OFF=$'\e[0m'
else RED=""; GREEN=""; DIM=""; OFF=""; fi

STEP=0
step() { STEP=$((STEP+1)); printf "[%d/%d] %-44s" "$STEP" "$TOTAL" "$1"; }
pass() { echo "${GREEN}ok${OFF}"; }
fail() {
  echo "${RED}FAILED${OFF}"
  echo ""
  echo "$1" | sed 's/^/    /'
  echo ""
  echo "${RED}VERIFY: RED${OFF} — step $STEP failed. The task is not finished."
  exit 1
}

# Every file git would commit: tracked + new, minus ignored and deleted.
repo_files() {
  git ls-files -co --exclude-standard -z | while IFS= read -r -d '' f; do
    [[ -f "$f" ]] && printf '%s\0' "$f"
  done
}

# Files under the given directories with the given extensions (regex).
source_files() {
  local dirs="$1" exts="$2"
  repo_files | tr '\0' '\n' | grep -E "^($dirs)/" | grep -E "\.($exts)$" || true
}

# ---------------------------------------------------------------------------
step "Build (interface + Rust)"
out=$(npm run build --silent 2>&1) || fail "npm run build failed:
$(echo "$out" | tail -25)"
out=$(cd src-tauri && cargo build --quiet 2>&1) || fail "cargo build failed:
$(echo "$out" | grep -E '^(error|  -->)' | head -25)"
pass

# ---------------------------------------------------------------------------
step "Automated tests"
out=$(cd src-tauri && cargo test --quiet 2>&1) || fail "cargo test failed:
$(echo "$out" | grep -E 'FAILED|panicked|^error' | head -25)"
if node -e "process.exit(require('./package.json').scripts?.test ? 0 : 1)"; then
  out=$(npm test --silent 2>&1) || fail "npm test failed:
$(echo "$out" | tail -25)"
fi
if [[ $LIVE -eq 1 ]]; then
  # --lib: --ignored would otherwise also run doc examples marked `ignore`
  out=$(cd src-tauri && cargo test --quiet --lib -- --ignored 2>&1) || fail "live tests failed:
$(echo "$out" | grep -E 'FAILED|panicked|^error' | head -25)"
fi
pass

# ---------------------------------------------------------------------------
step "No hard-coded user-visible text"
TSX=$(source_files "src" "tsx" | grep -v '^src/i18n/' || true)
hits=""
if [[ -n "$TSX" ]]; then
  # Text between a tag and its closing tag:   <h1>Hello</h1>
  # User-facing attributes:                    placeholder="Hello"
  # String literal as a child:                 >{'Hello'}
  hits=$(echo "$TSX" | tr '\n' '\0' | xargs -0 grep -nE \
    -e '[^=]>[^<>{}=]*[A-Za-z][^<>{}]*</' \
    -e '\b(placeholder|title|alt|aria-label|label)=["'"'"'][^"'"'"']*[A-Za-z]' \
    -e '>[[:space:]]*\{[[:space:]]*["'"'"'`][^"'"'"'`]*[A-Za-z]' 2>/dev/null || true)
fi
[[ -z "$hits" ]] || fail "User-visible text must come from src/i18n/en.json via t('...'):
$hits"
pass

# ---------------------------------------------------------------------------
step "No hard-coded colour"
STYLED=$(source_files "src" "ts|tsx|css"; [[ -f index.html ]] && echo index.html)
hits=""
if [[ -n "$STYLED" ]]; then
  palette='white|black|slate|gray|zinc|neutral|stone|red|orange|amber|yellow|lime|green|emerald|teal|cyan|sky|blue|indigo|violet|purple|fuchsia|pink|rose'
  utils='bg|text|border|ring|fill|stroke|from|via|to|outline|divide|placeholder|shadow|accent|caret|decoration'
  hits=$(echo "$STYLED" | tr '\n' '\0' | xargs -0 grep -nE \
    -e '#[0-9a-fA-F]{3}([0-9a-fA-F]{3}([0-9a-fA-F]{2})?)?\b' \
    -e '\b(rgb|rgba|hsl|hsla)\(' \
    -e "\b($utils)-($palette)(-[0-9]{2,3})?\b" \
    -e '-\[#' 2>/dev/null || true)
fi
[[ -z "$hits" ]] || fail "Colours must come from the theme (tailwind.config.js, liaotao-* classes):
$hits"
pass

# ---------------------------------------------------------------------------
step "No source file over $MAX_LINES lines"
long=""
while IFS= read -r f; do
  [[ -z "$f" ]] && continue
  n=$(wc -l < "$f" | tr -d ' ')
  (( n > MAX_LINES )) && long+="$f: $n lines"$'\n'
done < <(source_files "src|src-tauri/src" "ts|tsx|js|jsx|css|rs")
[[ -z "$long" ]] || fail "Split these files (limit $MAX_LINES lines):
$long"
pass

# ---------------------------------------------------------------------------
step "No unapproved dependency"
# One line per dependency: section:name=spec
npm_deps() {
  node -e '
    let s = ""; process.stdin.on("data", d => s += d).on("end", () => {
      const p = JSON.parse(s);
      for (const k of ["dependencies","devDependencies","optionalDependencies","peerDependencies"])
        for (const [n, v] of Object.entries(p[k] || {})) console.log(`npm ${k}:${n}=${v}`);
    });'
}
cargo_deps() {
  awk '
    /^\[/ { sec = ($0 ~ /^\[(.*-)?dependencies\]$/) ? $0 : ""; next }
    sec != "" && /^[A-Za-z0-9_-]+[[:space:]]*=/ {
      line = $0; gsub(/[[:space:]]+/, "", line); print "cargo " sec ":" line
    }'
}
git rev-parse -q --verify "refs/tags/$APPROVED_TAG" >/dev/null \
  || fail "Tag '$APPROVED_TAG' is missing. Only the maintainer creates it:
git tag -f $APPROVED_TAG"
approved=$( { git show "$APPROVED_TAG:package.json" | npm_deps
              git show "$APPROVED_TAG:src-tauri/Cargo.toml" | cargo_deps; } | sort)
current=$( { npm_deps < package.json; cargo_deps < src-tauri/Cargo.toml; } | sort)
diff_out=$(diff <(echo "$approved") <(echo "$current") | grep -E '^[<>]' \
  | sed -e 's/^</removed:/' -e 's/^>/added or changed:/' || true)
[[ -z "$diff_out" ]] || fail "Dependencies differ from the approved list (tag $APPROVED_TAG).
Stop and ask the maintainer; do not move the tag yourself.
$diff_out"
pass

# ---------------------------------------------------------------------------
step "No secret, no personal path"
SCANNED=$(repo_files | tr '\0' '\n' \
  | grep -vE '(^|/)(package-lock\.json|Cargo\.lock|verify\.sh)$' \
  | grep -vE '\.(png|icns|ico|jpg|jpeg|gif|webp|woff2?|ttf)$' || true)
hits=""
if [[ -n "$SCANNED" ]]; then
  hits=$(echo "$SCANNED" | tr '\n' '\0' | xargs -0 grep -nIE \
    -e '-----BEGIN [A-Z ]*PRIVATE KEY-----' \
    -e 'AKIA[0-9A-Z]{16}' \
    -e 'gh[pousr]_[A-Za-z0-9]{36,}' \
    -e 'github_pat_[A-Za-z0-9_]{50,}' \
    -e 'sk-[A-Za-z0-9_-]{20,}' \
    -e 'xox[abprs]-[A-Za-z0-9-]{10,}' \
    -e 'AIza[0-9A-Za-z_-]{35}' \
    -e '(api[_-]?key|secret|token|password)["'"'"']?[[:space:]]*[:=][[:space:]]*["'"'"'][^"'"'"'[:space:]]{16,}["'"'"']' \
    -e '/Users/[A-Za-z0-9._-]+/' \
    -e '/home/[A-Za-z0-9._-]+/' 2>/dev/null || true)
fi
[[ -z "$hits" ]] || fail "Remove secrets and personal paths (use \$HOME or a config value):
$hits"
pass

echo ""
echo "${GREEN}VERIFY: GREEN${OFF} ${DIM}— all $TOTAL checks passed$([[ $LIVE -eq 1 ]] && echo ', live tests included').${OFF}"
